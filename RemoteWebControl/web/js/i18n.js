// t("key", { name: "x" }) replaces {name}. Unknown keys fall back to English, then to the key itself.
export function t(key, params = {}) {
  const text = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function has(key) {
  return key in STRINGS.en;
}

// Static HTML: data-i18n="key" sets the text, data-i18n-attr="alt:key placeholder:key" sets attributes.
export function translatePage(root = document) {
  document.documentElement.lang = LANG;
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of node.dataset.i18nAttr.split(/\s+/)) {
      const [attribute, key] = pair.split(":");
      node.setAttribute(attribute, t(key));
    }
  }
}
